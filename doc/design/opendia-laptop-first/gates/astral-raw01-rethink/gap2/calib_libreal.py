"""Does the tail excess ride on library-intensity agreement? Design diagnostic (LDA, cross-fitted, raws 01 and 02).

Decoys inherit their target's library intensities ordinal by ordinal on a permuted sequence. Entrapment intensities are
predicted for their own sequence, so they follow real fragmentation rules (for example, proline enhancement). Real
interference is generated by those same rules, so a false target's library pattern could match random co-eluting signal
better than a decoy's does. If so, S_e/S_d should fall towards 1 when the features that use library intensities are removed.
Variants: all 20; minus 'library' group; minus library group and the library-weighted xcorr pair (xcorr_*_w).
Also reported: a proline-effect check of library realism, the share of precursors whose top-1 fragment is a y ion
starting at P.
"""
import os, sys, sqlite3, numpy as np, pandas as pd
sys.path.insert(0, '.')
RUN = os.environ.get('OPENDIA_RUN', '01')
import oswlike_score as S

def tail(sc):
    w = S.winners(np.arange(len(sc)), sc); kept, q = S.tdc_q(w, sc)
    dw = w[S.dec[w]]; ew = w[(~S.dec[w]) & S.entr[w]]; out = []
    for qq in (0.01, 0.02, 0.05):
        sel = kept[(~S.dec[kept]) & (q <= qq)]
        if len(sel) == 0: out.append('n/a'); continue
        t = sc[sel].min(); ke = int((sc[ew] >= t).sum()); kd = int((sc[dw] >= t).sum())
        out.append(f'{(ke / len(ew)) / max(1e-12, kd / len(dw)):.2f} ({ke}/{kd})')
    a = kept[(~S.dec[kept]) & (q <= 0.05)]
    return ' | '.join(out) + f' | q<=0.05 N {len(a)} FDP_c {S.entr[a].sum() * (1 + 1 / S.R_ENT) / max(1, len(a)):.3f}'

if RUN == '01':
    c = sqlite3.connect('/home/singjc/Documents/github/OpenMS-r1-benchmark-20261107/astral-entrapment-20261107/lib/library.pqp')
    q = """select p.ID pid, p.DECOY d, pe.UNMODIFIED_SEQUENCE seq, t.TYPE ty, t.ORDINAL ord, t.LIBRARY_INTENSITY li,
           group_concat(pr.PROTEIN_ACCESSION) acc from TRANSITION t join TRANSITION_PRECURSOR_MAPPING m on m.TRANSITION_ID=t.ID
           join PRECURSOR p on p.ID=m.PRECURSOR_ID join PRECURSOR_PEPTIDE_MAPPING pp on pp.PRECURSOR_ID=p.ID join PEPTIDE pe on pe.ID=pp.PEPTIDE_ID
           join PEPTIDE_PROTEIN_MAPPING ppm on ppm.PEPTIDE_ID=pe.ID join PROTEIN pr on pr.ID=ppm.PROTEIN_ID group by t.ID"""
    t = pd.read_sql(q, c)
    t['ent'] = t.acc.str.replace('DECOY_', '').str.split(',').apply(lambda a: all('_p_target' in x for x in a))
    t['grp'] = np.where(t.d == 1, 'decoy', np.where(t.ent, 'entrapment', 'human'))
    top = t.sort_values(['pid', 'li'], ascending=[True, False]).drop_duplicates('pid')
    top['startP'] = [(ty == 'y' and len(s) - o >= 0 and s[len(s) - o] == 'P') for s, ty, o in zip(top.seq, top.ty, top.ord)]
    hasP = top.seq.str[1:-1].str.contains('P')
    print('share of precursors whose top-1 fragment is a y ion starting at P (among peptides with an internal P):')
    print(top[hasP].groupby('grp').startP.mean().round(3).to_dict())

print(f'raw {RUN}: S_e/S_d at q<=0.01 / 0.02 / 0.05 cuts (entrapment/decoys above cut)')
L = S.GROUPS['library']; W = ['xcorr_coel_w', 'xcorr_shape_w']
for name, cols, main in (('all 20', S.ALL, 'xcorr_shape_w'),
                         ('minus library', [c_ for c_ in S.ALL if c_ not in L], 'xcorr_shape_w'),
                         ('minus library and weighted xcorr', [c_ for c_ in S.ALL if c_ not in L + W], 'xcorr_shape')):
    sc = S.crossfit(cols, main=main)
    print(f'  {name:34s} {tail(sc)}', flush=True)
